export function edhPowerLevel(meta: CardStripMeta): number {
  const lines = [...(meta.oracleText ?? '').split('\n'), ...(meta.keywords ?? [])].map((line) => line.toLowerCase())
  let level = 0
  for (const rule of POWER_RULES) {
    if (rule.points > level && lines.some((line) => rule.matches(line))) level = rule.points
  }
  if (meta.typeLine?.toLowerCase().includes('planeswalker')) level = Math.max(level, 6)
  const name = (meta.name ?? '').toLowerCase()
  if (NAMED_12.has(name)) level = Math.max(level, 12)
  if (NAMED_15.has(name)) level = Math.max(level, 15)
  if (NAMED_20.has(name)) level = Math.max(level, 20)
  return level
}
