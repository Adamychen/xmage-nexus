// Generates web/public/splash-i18n.js from the `splash` section of the
// web/src/i18n/locales/*.ts dictionaries, so the static Tauri splash screen
// speaks the same 9 languages as the React app (whose i18n coverage guard
// forces every key to exist in every language).
//
// Only the `splash` block is extracted (brace-matching on the TS source and
// evaluated as an object literal), so no TypeScript toolchain is needed.
// Splash values must stay plain single-quoted string literals.
//
// Usage: node scripts/gen-splash-i18n.mjs [--validate]
//   --validate: exit 1 when the committed file is stale.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const localesDir = path.join(root, 'web', 'src', 'i18n', 'locales')
const outFile = path.join(root, 'web', 'public', 'splash-i18n.js')

const LANGS = ['es', 'en', 'de', 'fr', 'ja', 'it', 'pt', 'ru', 'zhs']

function extractSplash(lang) {
  const src = fs.readFileSync(path.join(localesDir, `${lang}.ts`), 'utf8')
  const start = src.indexOf('splash: {')
  if (start < 0) throw new Error(`${lang}: no splash section`)
  let i = src.indexOf('{', start)
  let depth = 0
  let quote = null
  for (; i < src.length; i++) {
    const c = src[i]
    if (quote) {
      if (c === '\\') i++
      else if (c === quote) quote = null
    } else if (c === "'" || c === '"') {
      quote = c
    } else if (c === '{') {
      depth++
    } else if (c === '}') {
      depth--
      if (depth === 0) break
    }
  }
  if (depth !== 0) throw new Error(`${lang}: unbalanced braces in splash section`)
  const literal = src.slice(src.indexOf('{', start), i + 1)
  if (literal.includes('`') || literal.includes('${')) {
    throw new Error(`${lang}: splash values must be plain string literals`)
  }
  const splash = new Function(`return (${literal})`)()
  for (const [k, v] of Object.entries(splash)) {
    if (typeof v !== 'string' || v === '') throw new Error(`${lang}.splash.${k} must be a non-empty string`)
  }
  return splash
}

function render(i18n) {
  return `// GENERATED by scripts/gen-splash-i18n.mjs — do not edit by hand.
// Source of truth: the \`splash\` section of web/src/i18n/locales/*.ts.
window.__SPLASH_I18N = ${JSON.stringify(i18n, null, 2)};
window.__SPLASH_PICK_LANG = function (raw) {
  var nav = String(raw || '').toLowerCase().replace(/_/g, '-');
  if (window.__SPLASH_I18N[nav]) return nav;
  var base = nav.split('-')[0];
  if (window.__SPLASH_I18N[base]) return base;
  if (base === 'zh') return 'zhs';
  return 'en';
};
`
}

const i18n = {}
for (const lang of LANGS) i18n[lang] = extractSplash(lang)
const rendered = render(i18n)

if (process.argv.includes('--validate')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : ''
  if (current !== rendered) {
    console.error('splash-i18n.js is stale: run node scripts/gen-splash-i18n.mjs')
    process.exit(1)
  }
  console.log('splash-i18n.js is fresh')
} else {
  fs.writeFileSync(outFile, rendered)
  console.log(`wrote ${path.relative(root, outFile)} (${LANGS.length} languages)`)
}
