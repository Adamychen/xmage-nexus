#!/usr/bin/env node
// Generates the `keywords` i18n section from the curated tables in
// scripts/keywords-i18n/<lang>.mjs + web/src/data/mtgKeywords.ts (fallback).
//
// Key format (flat, so scripts/i18n-coverage.mjs parses them):
//   keywords: { <id>_name: '…', <id>_summary: '…', … }   (534 keys)
// Resolution per lang/id:
//   name    = table?.name    ?? EN canonical name (mtgKeywords.ts)
//   summary = table?.summary ?? enResolved summary (table EN ?? file text)
// Omitted curated ids (e.g. RU post-SNC mechanics with no Russian printing)
// fall back to English explicitly — counted in the coverage guard budget.
// Also injects wiki.rule_official / wiki.rule_ability_word (generic ruleSnippet
// lines that used to be hardcoded Spanish in mtgKeywords.ts).
// Usage: node scripts/gen-keywords-i18n.mjs [--check]   (--check = dry run)

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const LOCALES_DIR = path.join(ROOT, 'web/src/i18n/locales')
const TABLES_DIR = path.join(ROOT, 'scripts/keywords-i18n')
const CHECK = process.argv.includes('--check')

const LANGS = ['es', 'en', 'de', 'fr', 'it', 'pt', 'ru', 'ja', 'zhs']

const WIKI_RULES = {
  en: { rule_official: 'Official MTG rule.', rule_ability_word: 'Official MTG ability word.' },
  es: { rule_official: 'Regla oficial de MTG.', rule_ability_word: 'Palabra de habilidad oficial de MTG.' },
  de: { rule_official: 'Offizielle MTG-Regel.', rule_ability_word: 'Offizielles MTG-Fähigkeitswort.' },
  fr: { rule_official: 'Règle officielle de MTG.', rule_ability_word: 'Mot-clé officiel de MTG.' },
  it: { rule_official: 'Regola ufficiale di MTG.', rule_ability_word: 'Parola abilità ufficiale di MTG.' },
  pt: { rule_official: 'Regra oficial de MTG.', rule_ability_word: 'Palavra de habilidade oficial de MTG.' },
  ru: { rule_official: 'Официальное правило MTG.', rule_ability_word: 'Официальное кодовое слово MTG.' },
  ja: { rule_official: 'MTG公式ルール。', rule_ability_word: 'MTG公式能力語。' },
  zhs: { rule_official: 'MTG官方规则。', rule_ability_word: 'MTG官方异能词。' },
}

function parseKeywordsFile() {
  const src = fs.readFileSync(path.join(ROOT, 'web/src/data/mtgKeywords.ts'), 'utf8')
  const re = /\{\s*\n\s*id: "([^"]+)",\s*\n\s*name: "([^"]+)",\s*\n\s*nameEs: "([^"]+)",[\s\S]*?summary: "((?:[^"\\]|\\.)*)",/g
  const out = []
  let m
  while ((m = re.exec(src))) {
    out.push({ id: m[1], name: m[2], summary: m[3].replace(/\\n/g, ' ').replace(/\\"/g, '"').replace(/"\s*\+\s*"/g, '').replace(/\s+/g, ' ').trim() })
  }
  return out
}

function esc(v) {
  if (typeof v !== 'string' || v.length === 0) throw new Error('empty value')
  if (/[\n\r\t`]/.test(v)) throw new Error(`multiline/backtick value: ${v.slice(0, 60)}`)
  if (/\\/.test(v)) throw new Error(`backslash value: ${v.slice(0, 60)}`)
  if (/\$\{/.test(v)) throw new Error(`template value: ${v.slice(0, 60)}`)
  return v.replace(/'/g, "\\'")
}

const base = parseKeywordsFile()
if (base.length !== 267) throw new Error(`expected 267 keywords, got ${base.length}`)

const tables = {}
for (const lang of LANGS) {
  const mod = await import(path.join(TABLES_DIR, `${lang}.mjs`))
  tables[lang] = mod[`KW_${lang.toUpperCase()}`] ?? mod[Object.keys(mod)[0]]
}
for (const [lang, t] of Object.entries(tables)) {
  const extra = Object.keys(t).filter((k) => !base.some((b) => b.id === k))
  if (extra.length) throw new Error(`${lang}: unknown ids in table: ${extra.join(', ')}`)
}

const enResolved = {}
for (const b of base) {
  enResolved[b.id] = {
    name: b.name,
    summary: tables.en[b.id]?.summary ?? b.summary,
  }
  if (!enResolved[b.id].summary) throw new Error(`en: empty summary for ${b.id}`)
}

const resolved = {}
for (const lang of LANGS) {
  resolved[lang] = {}
  for (const b of base) {
    const t = tables[lang][b.id]
    const summary = lang === 'en'
      ? enResolved[b.id].summary
      : lang === 'es'
        ? (t?.summary ?? b.summary)
        : (t?.summary ?? enResolved[b.id].summary)
    const name = t?.name ?? b.name
    if (!summary) throw new Error(`${lang}: empty summary for ${b.id}`)
    resolved[lang][b.id] = { name, summary }
  }
}

function buildBlock(lang) {
  const lines = ['  // keywords:begin — GENERATED by scripts/gen-keywords-i18n.mjs, do not edit', '  keywords: {']
  for (const b of base) {
    const r = resolved[lang][b.id]
    lines.push(`    ${b.id}_name: '${esc(r.name)}',`)
    lines.push(`    ${b.id}_summary: '${esc(r.summary)}',`)
  }
  lines.push('  },', '  // keywords:end')
  return lines.join('\n')
}

const blockRe = /  \/\/ keywords:begin — GENERATED by scripts\/gen-keywords-i18n\.mjs, do not edit\n(?:.*\n)*?  \/\/ keywords:end/
const wikiAnchorRe = /(    shortcuts_skips: '(?:[^'\\]|\\')*',\n)(  \},)/
let totalIdentical = {}
for (const lang of LANGS) {
  const fp = path.join(LOCALES_DIR, `${lang}.ts`)
  let src = fs.readFileSync(fp, 'utf8')
  const block = buildBlock(lang)
  if (blockRe.test(src)) src = src.replace(blockRe, block)
  else src = src.replace(/\n\}\n?$/, `\n${block}\n}\n`)
  const w = WIKI_RULES[lang]
  const wikiAdd = `    rule_official: '${esc(w.rule_official)}',\n    rule_ability_word: '${esc(w.rule_ability_word)}',\n`
  if (src.includes('rule_official:')) {
    src = src.replace(/    rule_official: '(?:[^'\\]|\\')*',\n/, `    rule_official: '${esc(w.rule_official)}',\n`)
    src = src.replace(/    rule_ability_word: '(?:[^'\\]|\\')*',\n/, `    rule_ability_word: '${esc(w.rule_ability_word)}',\n`)
  } else if (wikiAnchorRe.test(src)) {
    src = src.replace(wikiAnchorRe, `$1${wikiAdd}$2`)
  } else {
    throw new Error(`${lang}: wiki anchor not found`)
  }
  if (!CHECK) fs.writeFileSync(fp, src)
  let identical = 0
  for (const b of base) {
    if (resolved[lang][b.id].name === enResolved[b.id].name) identical++
    if (resolved[lang][b.id].summary === enResolved[b.id].summary) identical++
  }
  totalIdentical[lang] = identical
}

console.log(`keywords: ${base.length} ids × 2 keys × ${LANGS.length} langs`)
for (const lang of LANGS) console.log(`  ${lang}: identical-to-en keyword values: ${totalIdentical[lang]}`)
if (CHECK) console.log('(dry run, no files written)')
